#pragma once

#define MIMIVENT_TRANSPORT_BLE 0
#define MIMIVENT_TRANSPORT_NAS 1
#define MIMIVENT_TRANSPORT_REMOTE 2

// 兼容正式版构建命令；新的构建入口应显式选择目标。
#ifndef MIMIVENT_TRANSPORT_TARGET
#if defined(MIMIVENT_ENABLE_WIFI) && MIMIVENT_ENABLE_WIFI
#define MIMIVENT_TRANSPORT_TARGET MIMIVENT_TRANSPORT_NAS
#else
#define MIMIVENT_TRANSPORT_TARGET MIMIVENT_TRANSPORT_BLE
#endif
#endif

#if MIMIVENT_TRANSPORT_TARGET < 0 || MIMIVENT_TRANSPORT_TARGET > 2
#error "Unknown MIMIVENT_TRANSPORT_TARGET"
#endif

// P1 仅预留 Remote，禁止误把 NAS 明文 MQTT 实现作为远程版发布。
#if MIMIVENT_TRANSPORT_TARGET == MIMIVENT_TRANSPORT_REMOTE
#if !defined(MIMIVENT_REMOTE_SCAFFOLD) || !MIMIVENT_REMOTE_SCAFFOLD
#error "Remote transport is not ready; use the explicit remote-scaffold development target"
#endif
#endif

#ifndef MIMIVENT_ENABLE_WIFI
#define MIMIVENT_ENABLE_WIFI (MIMIVENT_TRANSPORT_TARGET != MIMIVENT_TRANSPORT_BLE)
#endif
#ifndef MIMIVENT_WIFI_READ_CONTROL
#define MIMIVENT_WIFI_READ_CONTROL (MIMIVENT_TRANSPORT_TARGET == MIMIVENT_TRANSPORT_NAS)
#endif

#if MIMIVENT_TRANSPORT_TARGET == MIMIVENT_TRANSPORT_BLE && MIMIVENT_ENABLE_WIFI
#error "BLE target cannot enable WiFi"
#endif
#if MIMIVENT_TRANSPORT_TARGET != MIMIVENT_TRANSPORT_BLE && !MIMIVENT_ENABLE_WIFI
#error "Network target requires WiFi"
#endif
#if MIMIVENT_WIFI_READ_CONTROL && !MIMIVENT_ENABLE_WIFI
#error "MQTT requires WiFi"
#endif
#if MIMIVENT_TRANSPORT_TARGET == MIMIVENT_TRANSPORT_NAS && !MIMIVENT_WIFI_READ_CONTROL
#error "NAS target requires MQTT control"
#endif
#if MIMIVENT_TRANSPORT_TARGET == MIMIVENT_TRANSPORT_REMOTE && MIMIVENT_WIFI_READ_CONTROL
#error "Remote scaffold must not enable the NAS plaintext MQTT implementation"
#endif

#if MIMIVENT_TRANSPORT_TARGET == MIMIVENT_TRANSPORT_BLE
#define MIMIVENT_TRANSPORT_NAME "ble"
#elif MIMIVENT_TRANSPORT_TARGET == MIMIVENT_TRANSPORT_NAS
#define MIMIVENT_TRANSPORT_NAME "nas"
#else
#define MIMIVENT_TRANSPORT_NAME "remote"
#endif

#if MIMIVENT_TRANSPORT_TARGET == MIMIVENT_TRANSPORT_REMOTE
#define MIMIVENT_TRANSPORT_READY_JSON "false"
#else
#define MIMIVENT_TRANSPORT_READY_JSON "true"
#endif
